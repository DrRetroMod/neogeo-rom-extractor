def _cmc_encrypt_pair(c0: int, c1: int, table0hi: list[int], table0lo: list[int], table1: list[int], base: int, invert: int) -> tuple[int, int]:
    tmp = table1[(base & 0xFF) ^ _KOF2000_ADDRESS_0_7_XOR[(base >> 8) & 0xFF]]
    xor0 = (table0hi[(base >> 8) & 0xFF] & 0xFE) | (tmp & 0x01)
    xor1 = (tmp & 0xFE) | (table0lo[(base >> 8) & 0xFF] & 0x01)
    if invert:
        return c1 ^ xor1, c0 ^ xor0
    return c0 ^ xor0, c1 ^ xor1


def _cmc_decrypt_pair(c0: int, c1: int, table0hi: list[int], table0lo: list[int], table1: list[int], base: int, invert: int) -> tuple[int, int]:
    tmp = table1[(base & 0xFF) ^ _KOF2000_ADDRESS_0_7_XOR[(base >> 8) & 0xFF]]
    xor0 = (table0hi[(base >> 8) & 0xFF] & 0xFE) | (tmp & 0x01)
    xor1 = (tmp & 0xFE) | (table0lo[(base >> 8) & 0xFF] & 0x01)
    if invert:
        return c1 ^ xor0, c0 ^ xor1
    return c0 ^ xor0, c1 ^ xor1


def _scramble_c_address(rpos: int, rom_size: int, extra_xor: int) -> int:
    baser = rpos ^ extra_xor
    baser ^= _KOF2000_ADDRESS_8_15_XOR1[(baser >> 16) & 0xFF] << 8
    baser ^= _KOF2000_ADDRESS_8_15_XOR2[baser & 0xFF] << 8
    baser ^= _KOF2000_ADDRESS_16_23_XOR1[baser & 0xFF] << 16
    baser ^= _KOF2000_ADDRESS_16_23_XOR2[(baser >> 8) & 0xFF] << 16
    baser ^= _KOF2000_ADDRESS_0_7_XOR[(baser >> 8) & 0xFF]

    if rom_size == 0x3000000:
        if rpos < 0x2000000 // 4:
            baser &= (0x2000000 // 4) - 1
        else:
            baser = 0x2000000 // 4 + (baser & ((0x1000000 // 4) - 1))
    elif rom_size == 0x6000000:
        if rpos < 0x4000000 // 4:
            baser &= (0x4000000 // 4) - 1
        else:
            baser = 0x4000000 // 4 + (baser & ((0x1000000 // 4) - 1))
    else:
        baser &= (rom_size // 4) - 1
    return baser


def cmc50_gfx_encrypt(data: bytes | bytearray, *, extra_xor: int) -> bytes:
    """Encrypt Neo Geo C-ROM graphics using CMC50 tables."""
    _require_multiple_of_4(data, "CMC50 C-ROM")
    rom = bytearray(data)
    rom_size = len(rom)
    buf = bytearray(rom_size)

    # Address XOR layer.
    words = rom_size // 4
    for rpos in range(words):
        baser = _scramble_c_address(rpos, rom_size, extra_xor)
        src = 4 * rpos
        dst = 4 * baser
        buf[dst:dst + 4] = rom[src:src + 4]

    # Data XOR layer.
    t0_03 = _KOF2000_TYPE0_T03
    t0_12 = _KOF2000_TYPE0_T12
    t1_03 = _KOF2000_TYPE1_T03
    t1_12 = _KOF2000_TYPE1_T12
    a16_2 = _KOF2000_ADDRESS_16_23_XOR2

    for rpos in range(words):
        off = 4 * rpos
        r0, r3 = _cmc_encrypt_pair(
            buf[off + 0], buf[off + 3],
            t0_03, t0_12, t1_03,
            rpos,
            (rpos >> 8) & 1,
        )
        r1, r2 = _cmc_encrypt_pair(
            buf[off + 1], buf[off + 2],
            t0_12, t0_03, t1_12,
            rpos,
            ((rpos >> 16) ^ a16_2[(rpos >> 8) & 0xFF]) & 1,
        )
        rom[off + 0] = r0
        rom[off + 1] = r1
        rom[off + 2] = r2
        rom[off + 3] = r3

    return bytes(rom)


def cmc50_gfx_decrypt(data: bytes | bytearray, *, extra_xor: int) -> bytes:
    """Decrypt Neo Geo C-ROM graphics using CMC50 tables."""
    _require_multiple_of_4(data, "CMC50 C-ROM")
    source = bytearray(data)
    rom_size = len(source)
    buf = bytearray(rom_size)
    words = rom_size // 4

    t0_03 = _KOF2000_TYPE0_T03
    t0_12 = _KOF2000_TYPE0_T12
    t1_03 = _KOF2000_TYPE1_T03
    t1_12 = _KOF2000_TYPE1_T12
    a16_2 = _KOF2000_ADDRESS_16_23_XOR2

    # Data XOR layer.
    for rpos in range(words):
        off = 4 * rpos
        b0, b3 = _cmc_decrypt_pair(
            source[off + 0], source[off + 3],
            t0_03, t0_12, t1_03,
            rpos,
            (rpos >> 8) & 1,
        )
        b1, b2 = _cmc_decrypt_pair(
            source[off + 1], source[off + 2],
            t0_12, t0_03, t1_12,
            rpos,
            ((rpos >> 16) ^ a16_2[(rpos >> 8) & 0xFF]) & 1,
        )
        buf[off + 0] = b0
        buf[off + 1] = b1
        buf[off + 2] = b2
        buf[off + 3] = b3

    # Address XOR layer.
    out = bytearray(rom_size)
    for rpos in range(words):
        baser = _scramble_c_address(rpos, rom_size, extra_xor)
        src = 4 * baser
        dst = 4 * rpos
        out[dst:dst + 4] = buf[src:src + 4]

    return bytes(out)


def _generate_cs16(data: bytes | bytearray, size: int) -> int:
    return sum(data[:size]) & 0xFFFF


def _m1_address_descramble(address: int, key: int) -> int:
    block = (address >> 16) & 7
    aux = address & 0xFFFF
    aux ^= _bitswap(key, 12, 0, 2, 4, 8, 15, 7, 13, 10, 1, 3, 6, 11, 9, 14, 5)
    p = _M1_P1_DESCRAMBLE[block]
    aux = _bitswap(aux, p[15], p[14], p[13], p[12], p[11], p[10], p[9], p[8], p[7], p[6], p[5], p[4], p[3], p[2], p[1], p[0])
    aux ^= _M1_ADDRESS_0_7_XOR[(aux >> 8) & 0xFF]
    aux ^= _M1_ADDRESS_8_15_XOR[aux & 0xFF] << 8
    aux = _bitswap(aux, 7, 15, 14, 6, 5, 13, 12, 4, 11, 3, 10, 2, 9, 1, 8, 0)
    return (block << 16) | aux


def _m1_address_scramble(address: int, key: int) -> int:
    block = (address >> 16) & 7
    aux = address & 0xFFFF
    aux = _bitswap(aux, 14, 13, 10, 9, 7, 5, 3, 1, 15, 12, 11, 8, 6, 4, 2, 0)
    aux ^= _M1_ADDRESS_8_15_XOR[aux & 0xFF] << 8
    aux ^= _M1_ADDRESS_0_7_XOR[(aux >> 8) & 0xFF]
    p = _M1_P1_SCRAMBLE[block]
    aux = _bitswap(aux, p[15], p[14], p[13], p[12], p[11], p[10], p[9], p[8], p[7], p[6], p[5], p[4], p[3], p[2], p[1], p[0])
    aux ^= _bitswap(key, 12, 0, 2, 4, 8, 15, 7, 13, 10, 1, 3, 6, 11, 9, 14, 5)
    return (block << 16) | aux


def cmc50_m1_encrypt(data: bytes | bytearray) -> bytes:
    """Encrypt Neo Geo M1 Z80 data using the CMC50 M1 transform."""
    rom = bytes(data)
    if len(rom) < 0x10000:
        raise ValueError(f"CMC50 M1 data must be at least 0x10000 bytes; got 0x{len(rom):X}")
    key = _generate_cs16(rom, 0x10000)
    out = bytearray(len(rom))
    for i in range(len(rom)):
        out[i] = rom[_m1_address_scramble(i, key) % len(rom)]
    return bytes(out)


def cmc50_m1_decrypt(data: bytes | bytearray) -> bytes:
    """Decrypt Neo Geo M1 Z80 data using the CMC50 M1 transform."""
    rom = bytes(data)
    if len(rom) < 0x10000:
        raise ValueError(f"CMC50 M1 data must be at least 0x10000 bytes; got 0x{len(rom):X}")
    key = _generate_cs16(rom, 0x10000)
    out = bytearray(len(rom))
    for i in range(len(rom)):
        out[i] = rom[_m1_address_descramble(i, key) % len(rom)]
    return bytes(out)
